def loose_regex(old: str) -> str:
    """Biến 'old' thành regex: ký tự Hangul -> lớp ký tự, còn lại -> literal."""
    out = []
    for ch in old:
        if "\uac00" <= ch <= "\ud7a3":
            out.append(f"[{HANGUL}]+")
        elif "\u3131" <= ch <= "\u318e":
            out.append(f"[{HANGUL}]+")
        else:
            out.append(re.escape(ch))
    return "".join(out)


def main():
    hits, miss = 0, []
    files = {}

    def load(ep):
        if ep not in files:
            cp = HERE / "ja_cache" / f"tap{ep}.json"
            files[ep] = (cp, json.loads(cp.read_text(encoding="utf-8")))
        return files[ep][1]

    for ep, key, new in FULL:
        d = load(ep)
        v = d.get(key)
        if not isinstance(v, dict) or not isinstance(v.get("ja"), str):
            miss.append((ep, key, "KEY-MISS", ""))
            continue
        v["ja"] = new
        hits += 1

    for ep, key, pairs in SUB:
        d = load(ep)
        v = d.get(key)
        if not isinstance(v, dict) or not isinstance(v.get("ja"), str):
            miss.append((ep, key, "KEY-MISS", ""))
            continue
        ja = v["ja"]
        for old, new in pairs:
            if old in ja:
                ja = ja.replace(old, new)
                hits += 1
                continue
            rx = re.compile(loose_regex(old))
            m = rx.search(ja)
            if m:
                ja = ja[:m.start()] + new + ja[m.end():]
                hits += 1
            else:
                miss.append((ep, key, "TEXT-MISS", old[:44]))
        v["ja"] = ja

    total = len(FULL) + sum(len(p) for _, _, p in SUB)
    print(f"Ap dung {hits}/{total} quy tac.")
    if miss:
        print("\n!! KHONG KHAI THAC DUOC:")
        for ep, key, why, txt in miss:
            print(f"   Tap{ep} {key}: {why}  {txt}")
    else:
        print("Tat ca quy tac khop.")

    if not APPLY:
        print("\nDRY-RUN (chua ghi). Them --do de ghi.")
        return

    for ep, (cp, d) in files.items():
        shutil.copy2(cp, cp.with_suffix(".json.bak_fix"))
        cp.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"   da ghi tap{ep}.json (backup .bak_fix)")


if __name__ == "__main__":
    main()
