import re

# Định nghĩa regex của parser
JA_END = re.compile(r'[。！？][」』”"’）\]]*')

def ja_split(para):
    parts, last = [], 0
    for m in JA_END.finditer(para):
        parts.append(para[last:m.end()])
        last = m.end()
    tail = para[last:].strip()
    if tail:
        parts.append(tail)
    return parts

# Test 1.07 (muốn 4 câu)
s_1_07 = [
    "トレントン基地の私たち全員の目には、ウィリアムズ大佐はまさに完璧さの現れそのものでした。",
    "彼は常に冷静で、軍服の折り目一つに至るまで整然とし、部下に声を荒らげることなど一度もありませんでした。",
    "しかし、真相が暴かれた今――閲兵式での彼の穏やかな眼差しを思い出すたび、背筋が凍る思いがします。",
    "私たちは最も危険な捕食者のすぐ隣に立ちながら、心から敬意を払って頭を垂れていたのです。"
]
print("1.07 sentences:", sum(len(ja_split(p)) for p in s_1_07))

